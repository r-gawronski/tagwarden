// ErrSBOMGeneratorUnavailable means the SBOM sidecar did not start or did
// not answer. The run fails so that the Job retries.
var ErrSBOMGeneratorUnavailable = errors.New("sync: SBOM generator sidecar unavailable")

// SBOM turns on SBOM generation for an image mirror (docs/design/sbom.md):
// each image child of a tag gets an SBOM referrer, generated by the sidecar
// from the layout or, under PreferUpstream, copied from upstream.
type SBOM struct {
	// Mode is PreferUpstream or Generate.
	Mode   v1alpha1.SBOMMode
	Format sbom.Format
	// Required keeps a new tag whose SBOMs cannot all be attached from
	// being published.
	Required bool
	// Version is the pinned generator version. The sidecar must report the
	// same major.minor.
	Version string
	// LayoutDir and ScanDir are syncspec.LayoutDir and syncspec.ScanDir.
	LayoutDir, ScanDir string
	// Timeout is the generation timeout of one platform child.
	Timeout time.Duration
	// JavaDB is pulled from the target registry before the first
	// generation. Nil means JAR files are skipped.
	JavaDB *name.Tag
	// Now and Poll are for tests: the clock and the sidecar poll interval.
	Now  func() time.Time
	Poll time.Duration
}

// Sources of the SBOM of a platform child.
const (
	SBOMSourceGenerated = "generated"
	SBOMSourceUpstream  = "upstream"
	// SBOMSourcePresent is an SBOM the target already had.
	SBOMSourcePresent = "present"
)

// SBOMResult is the SBOM outcome of one tag.
type SBOMResult struct {
	Platforms []SBOMPlatform
	// Reason is the first failure, a syncspec SBOM reason; empty when every
	// image child has an SBOM. Detail explains it in a few words.
	Reason, Detail string
}

func (r *SBOMResult) fail(reason, detail string) {
	if r.Reason == "" {
		r.Reason, r.Detail = reason, detail
	}
}

// SBOMPlatform is the SBOM of one platform child.
type SBOMPlatform struct {
	Platform, Digest string
	Source           string
	// Referrer is the digest of the child-level referrer.
	Referrer    string
	Size        int64
	JavaScanned bool
}

// sbomError fails a tag that is not published because of Required.
type sbomError struct{ a Artifact }

func (e *sbomError) Error() string {
	return fmt.Sprintf("SBOM %s: %s, tag not published", e.a.SBOM.Reason, e.a.SBOM.Detail)
}

type sbomState struct {
	SBOM
	root    *os.Root
	checked bool
	// problem is set when the sidecar cannot generate; every generation
	// fails with it.
	problem     string
	unavailable bool
	javaScanned bool
}

func (b *sbomState) now() time.Time {
	if b.Now != nil {
		return b.Now()
	}
	return time.Now()
}

func (b *sbomState) generator() string { return "trivy/" + b.Version }

// ensure checks the sidecar once per run: its version and, with the Java
// DB, the DB in the scan volume.
func (b *sbomState) ensure(ctx context.Context, s *syncer) {
	if b.checked {
		return
	}
	b.checked = true
	var err error
	if b.root, err = os.OpenRoot(b.ScanDir); err != nil {
		b.problem = "scan volume missing"
		return
	}
	var raw []byte
	err = wait(ctx, b.Poll, b.Timeout, func() (bool, error) {
		var err error
		raw, err = readSmall(b.root, syncspec.ScanVersionFile, maxVersionBytes)
		if errors.Is(err, os.ErrNotExist) {
			return false, nil
		}
		return true, err
	})
	var v trivyVersion
	switch {
	case err != nil:
		b.problem, b.unavailable = "generator sidecar not running", true
		return
	case json.Unmarshal(raw, &v) != nil:
		b.problem = "generator sidecar: invalid version"
		return
	case !sameMinor(v.Version, b.Version):
		b.problem = fmt.Sprintf("generator version mismatch, want %s.x", minor(b.Version))
		return
	}
	if b.JavaDB != nil {
		if !s.javaDB(ctx, b.root, *b.JavaDB) {
			b.problem = "java DB unavailable"
			return
		}
		b.javaScanned = true
	}
}

// sbomItem is an SBOM to attach to child c: a document (generated, or
// read from a present child referrer when only its index-level copy is
// missing) or an upstream referrer to copy.
type sbomItem struct {
	c         child
	doc       []byte
	generator string
	java      bool
	// childDone means the child-level referrer is on the target already.
	childDone bool
	childRef  string
	up        *remote.Descriptor
}

// newSBOMs prepares the SBOMs of a new tag from the layout of desc.
// Nothing is pushed. It returns the layout artifact to push from, nil when
// the layout could not be written for lack of space.
func (s *syncer) newSBOMs(ctx context.Context, desc *remote.Descriptor, budget *int64) (remote.Taggable, []sbomItem, *SBOMResult, error) {
	r := &SBOMResult{}
	t, children, err := s.layout(s.sbom.LayoutDir, desc)
	switch {
	case errors.Is(err, syscall.ENOSPC):
		r.fail(syncspec.SBOMGenerationFailed, "work volume full, raise generator.storage")
		return nil, nil, r, nil
	case err != nil:
		return nil, nil, nil, fmt.Errorf("write layout: %w", err)
	}
	var items []sbomItem
	images := 0
	for _, c := range children {
		if c.skip {
			continue
		}
		images++
		if it, ok := s.prepareSBOM(ctx, c, budget, r); ok {
			items = append(items, it)
		}
	}
	if images == 0 {
		r.fail(syncspec.SBOMGenerationFailed, "no image manifests")
	}
	return t, items, r, nil
}

// prepareSBOM decides the SBOM of image child c of the layout: under
// PreferUpstream a valid upstream referrer, otherwise a generated
// document. Under Required it stops at the first failure.
func (s *syncer) prepareSBOM(ctx context.Context, c child, budget *int64, r *SBOMResult) (sbomItem, bool) {
	switch {
	case r.Reason != "" && s.sbom.Required:
		return sbomItem{}, false
	case c.unusable != "":
		r.fail(syncspec.SBOMGenerationFailed, c.unusable)
		return sbomItem{}, false
	}
	if s.sbom.Mode == v1alpha1.SBOMModePreferUpstream {
		if up := s.upstreamSBOM(ctx, c.digest, budget); up != nil {
			return sbomItem{c: c, up: up}, true
		}
	}
	doc, reason, detail := s.generateSBOM(ctx, c.digest, budget)
	if reason != "" {
		r.fail(reason, detail)
		return sbomItem{}, false
	}
	return sbomItem{c: c, doc: doc, generator: s.sbom.generator(), java: s.sbom.javaScanned}, true
}

// upstreamSBOM returns the first upstream referrer of child d that counts
// as its SBOM (sbom.Upstream), with a valid document and within the
// referrer budget, or nil.
func (s *syncer) upstreamSBOM(ctx context.Context, d v1.Hash, budget *int64) *remote.Descriptor {
	f := s.sbom.Format
	opts := append(slices.Clone(s.req.SourceOpts), remote.Reuse(s.src), remote.WithContext(ctx))
	idx, err := remote.Referrers(s.req.Source.Digest(d.String()), opts...)
	if err != nil {
		return nil
	}
	im, err := idx.IndexManifest()
	if err != nil {
		return nil
	}
	for _, m := range im.Manifests {
		if at := m.ArtifactType; !m.MediaType.IsImage() || sbom.Reserved(m.Annotations) ||
			at != "" && at != string(f.MediaType()) && at != sbom.EmptyConfigMediaType {
			continue
		}
		desc, err := s.src.Get(ctx, s.req.Source.Digest(m.Digest.String()))
		if err != nil {
			continue
		}
		layer, err := sbom.Upstream(desc.Manifest, d, f)
		if err != nil {
			continue
		}
		used := *budget
		if s.checkReferrerSize(ctx, desc, &used) != nil || !validLayer(desc, layer, f) {
			continue
		}
		*budget = used
		return desc
	}
	return nil
}

// validLayer reads the SBOM layer of desc to its end, so the registry
// reader checks its digest, and checks the document.
func validLayer(desc *remote.Descriptor, layer v1.Descriptor, f sbom.Format) bool {
	img, err := desc.Image()
	if err != nil {
		return false
	}
	l, err := img.LayerByDigest(layer.Digest)
	if err != nil {
		return false
	}
	rc, err := l.Compressed()
	if err != nil {
		return false
	}
	defer func() { _ = rc.Close() }()
	_, err = sbom.Check(rc, f, 0)
	return err == nil
}

// generateSBOM asks the sidecar for the SBOM of manifest d of the layout
// and checks it. The sidecar is untrusted: every file is read through the
// scan root, must be a regular file and has a size cap; a missing, late,
// malformed or oversized answer is a failure. It returns the document or a
// failure reason and detail.
func (s *syncer) generateSBOM(ctx context.Context, d v1.Hash, budget *int64) ([]byte, string, string) {
	b := s.sbom
	b.ensure(ctx, s)
	if b.problem != "" {
		return nil, syncspec.SBOMGenerationFailed, b.problem
	}
	if d.Algorithm != "sha256" || !hexDigest.MatchString(d.Hex) {
		return nil, syncspec.SBOMGenerationFailed, "unsupported digest"
	}
	limit := sbom.MaxSize
	if s.req.MaxArtifactSize > 0 {
		if limit = min(limit, s.req.MaxArtifactSize-*budget); limit <= 0 {
			return nil, syncspec.SBOMTooLarge, "referrer budget (maxArtifactSize) used up"
		}
	}
	file := d.Hex + "." + b.Format.TrivyFormat()
	req, out := syncspec.ScanReqDir+"/"+file, syncspec.ScanOutDir+"/"+file
	for _, f := range []string{out + ".json", out + ".exit", req} {
		if err := b.root.Remove(f); err != nil && !errors.Is(err, os.ErrNotExist) {
			return nil, syncspec.SBOMGenerationFailed, "scan volume not writable"
		}
	}
	// Each answer is removed after it is read: SBOMs share the scan volume.
	defer func() {
		_ = b.root.Remove(out + ".json")
		_ = b.root.Remove(out + ".exit")
	}()
	f, err := b.root.OpenFile(req, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0o644)
	if err != nil {
		return nil, syncspec.SBOMGenerationFailed, "generation request not writable"
	}
	_ = f.Close()

	var exit []byte
	err = wait(ctx, b.Poll, b.Timeout+b.Timeout/4, func() (bool, error) {
		var err error
		exit, err = readSmall(b.root, out+".exit", 16)
		if errors.Is(err, os.ErrNotExist) {
			return false, nil
		}
		return true, err
	})
	switch {
	case errors.Is(err, errWaitTimeout):
		// A request the sidecar never picked up means it is not running.
		if _, serr := b.root.Lstat(req); serr == nil {
			_ = b.root.Remove(req)
			b.problem, b.unavailable = "generator sidecar did not answer", true
			return nil, syncspec.SBOMGenerationFailed, b.problem
		}
		return nil, syncspec.SBOMGenerationFailed, "generation timed out"
	case err != nil:
		return nil, syncspec.SBOMGenerationFailed, "invalid generator exit file"
	}
	if code := strings.TrimSpace(string(exit)); code != "0" {
		return nil, syncspec.SBOMGenerationFailed, "generator exited with an error"
	}
	rf, err := openRegular(b.root, out+".json")
	if err != nil {
		return nil, syncspec.SBOMGenerationFailed, "SBOM missing"
	}
	defer func() { _ = rf.Close() }()
	doc, err := sbom.Check(rf, b.Format, limit)
	switch {
	case errors.Is(err, sbom.ErrTooLarge):
		return nil, syncspec.SBOMTooLarge, fmt.Sprintf("SBOM larger than %d bytes", limit)
	case err != nil:
		return nil, syncspec.SBOMGenerationFailed, "invalid SBOM"
	}
	*budget += int64(len(doc))
	return doc, "", ""
}

// attachSBOMs pushes the prepared SBOMs. A document becomes a referrer of
// its child and, when top is an index, a copy with the platform annotation
// becomes a referrer of the index; both share the layer blob. An upstream
// referrer is copied as it is.
func (s *syncer) attachSBOMs(ctx context.Context, top *v1.Descriptor, items []sbomItem, r *SBOMResult) {
	created := s.sbom.now()
	for _, it := range items {
		p := SBOMPlatform{Platform: it.c.platform, Digest: it.c.digest.String()}
		if it.up != nil {
			if err := s.ensure(ctx, it.up); err != nil {
				r.fail(syncspec.SBOMAttachFailed, short(err))
				continue
			}
			p.Source, p.Referrer = SBOMSourceUpstream, it.up.Digest.String()
			if m, err := v1.ParseManifest(bytes.NewReader(it.up.Manifest)); err == nil && len(m.Layers) == 1 {
				p.Size = m.Layers[0].Size
			}
			r.Platforms = append(r.Platforms, p)
			continue
		}
		ref := sbom.Referrer{
			Format: s.sbom.Format, Document: it.doc, Subject: it.c.desc,
			Generator: it.generator, JavaScanned: it.java, Created: created,
		}
		p.Source, p.Size, p.JavaScanned, p.Referrer = SBOMSourceGenerated, int64(len(it.doc)), it.java, it.childRef
		if it.childDone {
			p.Source = SBOMSourcePresent
		} else {
			d, err := s.pushReferrer(ctx, ref)
			if err != nil {
				r.fail(syncspec.SBOMAttachFailed, short(err))
				continue
			}
			p.Referrer = d.String()
		}
		if top != nil {
			ref.Subject, ref.Platform = *top, indexPlatform(it.c)
			if _, err := s.pushReferrer(ctx, ref); err != nil {
				r.fail(syncspec.SBOMAttachFailed, short(err))
				continue
			}
		}
		r.Platforms = append(r.Platforms, p)
	}
}

func (s *syncer) pushReferrer(ctx context.Context, ref sbom.Referrer) (v1.Hash, error) {
	img, err := ref.Image()
	if err != nil {
		return v1.Hash{}, err
	}
	d, err := img.Digest()
	if err != nil {
		return v1.Hash{}, err
	}
	return d, s.push(ctx, d, img)
}

// indexPlatform names the platform of an index-level copy. A child without
// a platform in the index gets unknown/unknown, so the copy is never taken
// for a child-level referrer.
func indexPlatform(c child) string {
	if c.platform == "" {
		return "unknown/unknown"
	}
	return c.platform
}

// indexOf returns the descriptor of desc when it is an index, else nil.
func indexOf(desc *remote.Descriptor) *v1.Descriptor {
	if !desc.MediaType.IsIndex() {
		return nil
	}
	d := desc.Descriptor
	return &d
}

// presentSBOMs checks the SBOMs of digest, which the target already has
// under the tag, and attaches the missing ones. It reads the children from
// the target and, only when an SBOM must be generated, fetches the digest
// into the layout from p and repo. A published tag is never untagged:
// failures are only reported.
func (s *syncer) presentSBOMs(ctx context.Context, p *remote.Puller, repo name.Repository, digest string, budget *int64) *SBOMResult {
	r := &SBOMResult{}
	top, err := s.dst.Get(ctx, s.req.Target.Digest(digest))
	if err != nil {
		r.fail(syncspec.SBOMMissing, "fetch target manifest: "+short(err))
		return r
	}
	children, err := s.targetChildren(ctx, top)
	if err != nil {
		r.fail(syncspec.SBOMMissing, short(err))
		return r
	}
	idx := indexOf(top)
	var topRefs []v1.Descriptor
	if idx != nil {
		if topRefs, err = s.targetReferrers(ctx, idx.Digest); err != nil {
			r.fail(syncspec.SBOMMissing, "list target referrers: "+short(err))
			return r
		}
	}
	var items []sbomItem
	var missing []child
	images := 0
	for _, c := range children {
		if c.skip {
			continue
		}
		images++
		if c.unusable != "" {
			r.fail(syncspec.SBOMGenerationFailed, c.unusable)
			continue
		}
		refs, err := s.targetReferrers(ctx, c.digest)
		if err != nil {
			r.fail(syncspec.SBOMMissing, "list target referrers: "+short(err))
			continue
		}
		pl := SBOMPlatform{Platform: c.platform, Digest: c.digest.String(), Source: SBOMSourcePresent}
		if i := slices.IndexFunc(refs, func(d v1.Descriptor) bool { return sbom.Generated(d, s.sbom.Format, "") }); i >= 0 {
			gen := refs[i]
			pl.Referrer, pl.Size, pl.JavaScanned = gen.Digest.String(), gen.Size, gen.Annotations[sbom.AnnotationJavaScanned] != "false"
			if idx != nil && !slices.ContainsFunc(topRefs, func(d v1.Descriptor) bool { return sbom.Generated(d, s.sbom.Format, indexPlatform(c)) }) {
				it, err := s.presentCopy(ctx, c, gen)
				if err != nil {
					r.fail(syncspec.SBOMMissing, short(err))
					continue
				}
				items = append(items, it)
				continue
			}
			r.Platforms = append(r.Platforms, pl)
			continue
		}
		if s.sbom.Mode == v1alpha1.SBOMModePreferUpstream {
			if d := s.targetUpstream(ctx, c.digest, refs); d != "" {
				pl.Referrer = d
				r.Platforms = append(r.Platforms, pl)
				continue
			}
		}
		missing = append(missing, c)
	}
	if images == 0 {
		r.fail(syncspec.SBOMGenerationFailed, "no image manifests")
	}
	if len(missing) > 0 {
		items = append(items, s.missingSBOMs(ctx, p, repo, digest, missing, budget, r)...)
	}
	s.attachSBOMs(ctx, idx, items, r)
	return r
}

// missingSBOMs fetches digest into the layout and prepares the SBOMs of
// the missing children.
func (s *syncer) missingSBOMs(ctx context.Context, p *remote.Puller, repo name.Repository, digest string, missing []child, budget *int64, r *SBOMResult) []sbomItem {
	desc, err := p.Get(ctx, repo.Digest(digest))
	if err != nil {
		r.fail(syncspec.SBOMMissing, "fetch manifest: "+short(err))
		return nil
	}
	if err := s.checkSize(ctx, p, repo, desc); err != nil {
		r.fail(syncspec.SBOMTooLarge, short(err))
		return nil
	}
	_, laid, err := s.layout(s.sbom.LayoutDir, desc)
	switch {
	case errors.Is(err, syscall.ENOSPC):
		r.fail(syncspec.SBOMGenerationFailed, "work volume full, raise generator.storage")
		return nil
	case err != nil:
		r.fail(syncspec.SBOMGenerationFailed, "write layout: "+short(err))
		return nil
	}
	var items []sbomItem
	for _, c := range missing {
		// The layout's own classification decides, as for a new tag.
		i := slices.IndexFunc(laid, func(l child) bool { return l.digest == c.digest })
		if i < 0 || laid[i].skip {
			continue
		}
		if it, ok := s.prepareSBOM(ctx, laid[i], budget, r); ok {
			items = append(items, it)
		}
	}
	return items
}

// presentCopy reads the document of the generated child referrer gen from
// the target, to attach its missing index-level copy.
func (s *syncer) presentCopy(ctx context.Context, c child, gen v1.Descriptor) (sbomItem, error) {
	desc, err := s.dst.Get(ctx, s.req.Target.Digest(gen.Digest.String()))
	if err != nil {
		return sbomItem{}, fmt.Errorf("fetch target SBOM: %w", err)
	}
	m, err := v1.ParseManifest(bytes.NewReader(desc.Manifest))
	if err != nil || len(m.Layers) != 1 {
		return sbomItem{}, errors.New("target SBOM referrer: unexpected manifest")
	}
	img, err := desc.Image()
	if err != nil {
		return sbomItem{}, err
	}
	l, err := img.LayerByDigest(m.Layers[0].Digest)
	if err != nil {
		return sbomItem{}, err
	}
	rc, err := l.Compressed()
	if err != nil {
		return sbomItem{}, err
	}
	defer func() { _ = rc.Close() }()
	doc, err := sbom.Check(rc, s.sbom.Format, 0)
	if err != nil {
		return sbomItem{}, fmt.Errorf("target SBOM: %w", err)
	}
	return sbomItem{
		c: c, doc: doc, generator: m.Annotations[sbom.AnnotationGenerator],
		java: m.Annotations[sbom.AnnotationJavaScanned] != "false", childDone: true, childRef: gen.Digest.String(),
	}, nil
}

// targetUpstream returns the digest of a referrer of child d on the target
// that counts as an upstream SBOM of the configured format, or "". The
// referrer was checked when it was copied; only its manifest is read.
func (s *syncer) targetUpstream(ctx context.Context, d v1.Hash, refs []v1.Descriptor) string {
	f := s.sbom.Format
	for _, m := range refs {
		if at := m.ArtifactType; !m.MediaType.IsImage() || sbom.Reserved(m.Annotations) ||
			at != "" && at != string(f.MediaType()) && at != sbom.EmptyConfigMediaType {
			continue
		}
		desc, err := s.dst.Get(ctx, s.req.Target.Digest(m.Digest.String()))
		if err != nil {
			continue
		}
		if _, err := sbom.Upstream(desc.Manifest, d, f); err == nil {
			return m.Digest.String()
		}
	}
	return ""
}

func (s *syncer) targetReferrers(ctx context.Context, d v1.Hash) ([]v1.Descriptor, error) {
	opts := append(slices.Clone(s.req.TargetOpts), remote.Reuse(s.dst), remote.WithContext(ctx))
	idx, err := remote.Referrers(s.req.Target.Digest(d.String()), opts...)
	if err != nil {
		return nil, err
	}
	im, err := idx.IndexManifest()
	if err != nil {
		return nil, err
	}
	return im.Manifests, nil
}

// targetChildren lists the children of desc, read from the target, with
// the content rule of writeLayout: a manifest whose layers are labelled
// attestations and are valid JSON is skipped, a nested index is unusable.
func (s *syncer) targetChildren(ctx context.Context, desc *remote.Descriptor) ([]child, error) {
	classify := func(c *child, d *remote.Descriptor) error {
		mf, err := v1.ParseManifest(bytes.NewReader(d.Manifest))
		if err != nil {
			return err
		}
		if !vuln.SkipManifest(layerTypes(mf)) {
			return nil
		}
		img, err := d.Image()
		if err != nil {
			return err
		}
		c.skip = jsonLayers(mf, func(h v1.Hash) (io.ReadCloser, error) {
			l, err := img.LayerByDigest(h)
			if err != nil {
				return nil, err
			}
			return l.Compressed()
		})
		return nil
	}
	if !desc.MediaType.IsIndex() {
		if !desc.MediaType.IsImage() {
			return nil, fmt.Errorf("unsupported media type %s", desc.MediaType)
		}
		c := child{digest: desc.Digest, desc: desc.Descriptor}
		if err := classify(&c, desc); err != nil {
			return nil, err
		}
		return []child{c}, nil
	}
	im, err := v1.ParseIndexManifest(bytes.NewReader(desc.Manifest))
	if err != nil {
		return nil, err
	}
	out := make([]child, 0, len(im.Manifests))
	for _, m := range im.Manifests {
		c := child{digest: m.Digest, desc: m}
		if m.Platform != nil {
			c.platform = m.Platform.String()
		}
		switch {
		case m.MediaType.IsIndex():
			c.unusable = "nested index"
		case m.MediaType.IsImage():
			d, err := s.dst.Get(ctx, s.req.Target.Digest(m.Digest.String()))
			if err != nil {
				return nil, fmt.Errorf("fetch target manifest %s: %w", m.Digest, err)
			}
			if err := classify(&c, d); err != nil {
				return nil, err
			}
		default:
			return nil, fmt.Errorf("unsupported child media type %s", m.MediaType)
		}
		out = append(out, c)
	}
	return out, nil
}
